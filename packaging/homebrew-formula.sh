#!/usr/bin/env bash
# Prints the Homebrew formula for one release: homebrew-formula.sh VERSION SHA256SUMS
# The release workflow commits its output to adriandeleon/homebrew-tap as Formula/jkit.rb.
set -euo pipefail

version=${1:?usage: homebrew-formula.sh VERSION SHA256SUMS}
sums=${2:?usage: homebrew-formula.sh VERSION SHA256SUMS}

# a release version: 1.2.3 or 1.2.3-rc.1, nothing a formula or manifest could be tricked by
if ! [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?$ ]]; then
  echo "not a release version: '$version' (expected 1.2.3 or 1.2.3-rc.1)" >&2
  exit 1
fi
repo=${GITHUB_REPOSITORY:-adriandeleon/jkit}
base="https://github.com/$repo/releases/download/v$version"

sha() {
  local file="jkit-$version-$1.tar.gz" s
  s=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  [ -n "$s" ] || { echo "no checksum for $file in $sums" >&2; exit 1; }
  echo "$s"
}
# looked up before the heredoc: a failed $(sha ...) inside it would only exit its subshell
sha_macos_aarch64=$(sha macos-aarch64)
sha_macos_x64=$(sha macos-x64)
sha_linux_aarch64=$(sha linux-aarch64)
sha_linux_x64=$(sha linux-x64)

cat <<EOF
# Generated by packaging/homebrew-formula.sh in $repo; edits here are overwritten each release.
class Jkit < Formula
  desc "Installs and switches JDKs, Maven, Gradle and sbt"
  homepage "https://jkit-project.dev"
  version "$version"
  # jkit's own code is MIT; the binary also carries the libraries and Java runtime parts listed
  # in THIRD-PARTY-NOTICES (the main licenses; the notices file has every one)
  license all_of: [
    "MIT",
    "Apache-2.0",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "BSL-1.0",
    "MPL-2.0",
    "Unicode-3.0",
    "Zlib",
    { "GPL-2.0-only" => { with: "Classpath-exception-2.0" } },
  ]
  # the binary links the system zlib (libz.so.1) on Linux
  uses_from_macos "zlib"

  on_macos do
    depends_on macos: :sequoia

    on_arm do
      url "$base/jkit-$version-macos-aarch64.tar.gz"
      sha256 "$sha_macos_aarch64"
    end
    on_intel do
      url "$base/jkit-$version-macos-x64.tar.gz"
      sha256 "$sha_macos_x64"
    end
  end

  on_linux do
    on_arm do
      url "$base/jkit-$version-linux-aarch64.tar.gz"
      sha256 "$sha_linux_aarch64"
    end
    on_intel do
      url "$base/jkit-$version-linux-x64.tar.gz"
      sha256 "$sha_linux_x64"
    end
  end

  def install
    bin.install "jkit"
    prefix.install "LICENSE", "THIRD-PARTY-NOTICES"
    generate_completions_from_executable(bin/"jkit", "completion", shells: [:bash])
  end

  def caveats
    <<~EOS
      To switch versions with \`jkit use\` and on cd, add the shell hook:
        jkit hook --install --auto-switch
    EOS
  end

  test do
    assert_equal "jkit #{version}", shell_output("#{bin}/jkit --version").strip
    ENV["JKIT_HOME"] = testpath/"jkit-home"
    assert_match "schemaVersion", shell_output("#{bin}/jkit list --json")
  end
end
EOF
