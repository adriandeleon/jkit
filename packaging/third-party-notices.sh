#!/usr/bin/env bash
# Builds THIRD-PARTY-NOTICES, the notices for the libraries compiled into the jkit binary.
#
#   packaging/third-party-notices.sh          rewrite THIRD-PARTY-NOTICES
#   packaging/third-party-notices.sh --check  fail if it is stale (CI runs this)
#
# The component list is packaging/third-party/components.tsv. Both modes first ask Maven for the
# runtime dependencies of jkit-cli and fail if they differ from that list, so a dependency change
# can't ship without its notices. NOTICE and license texts are copied verbatim out of the jars in
# the local Maven repository (MAVEN_REPO, default ~/.m2/repository), so run a build first.
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
table="$root/packaging/third-party/components.tsv"
target="$root/THIRD-PARTY-NOTICES"
repo=${MAVEN_REPO:-$HOME/.m2/repository}
check=false
case "${1:-}" in
  --check) check=true ;;
  "") ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# 1. The dependency set Maven resolves must match the table.
(cd "$root" && ./mvnw -B -q -pl jkit-cli -am dependency:list -DincludeScope=runtime \
  -DexcludeGroupIds=dev.jkit -DoutputFile="$tmp/deps.txt" -DappendOutput=true) >&2
awk -F: '/^ +[^ ]+:[^ ]+:/ { sub(/^ +/, ""); print $1 ":" $2 ":" $4 }' "$tmp/deps.txt" \
  | sort -u > "$tmp/resolved"
awk -F'\t' '!/^#/ && NF { print $1 ":" $2 }' "$table" | sort -u > "$tmp/listed"
if ! diff -u --label components.tsv --label maven "$tmp/listed" "$tmp/resolved" >&2; then
  echo "the runtime dependencies changed: update $table (license, copyright, notice files)" >&2
  echo "and run packaging/third-party-notices.sh" >&2
  exit 1
fi

# 2. Render the notices.
jar_of() { # group:artifact version
  local g=${1%%:*} a=${1#*:}
  echo "$repo/${g//.//}/$a/$2/$a-$2.jar"
}

{
  cat <<'EOF'
jkit third-party notices
========================

The jkit binary is compiled ahead of time with GraalVM Native Image. Besides jkit's own code
(MIT License, see LICENSE), it contains the libraries listed below, under their own licenses,
and the GraalVM Community Edition and OpenJDK runtime, which is licensed under the GNU General
Public License version 2 with the Classpath Exception
(https://github.com/oracle/graal/blob/master/LICENSE, https://openjdk.org/legal/gplv2+ce.html).

This file is generated by packaging/third-party-notices.sh; do not edit it by hand.

Components
----------

EOF
  while IFS=$'\t' read -r ga version license copyright url files; do
    [[ -z "$ga" || "$ga" == \#* ]] && continue
    printf '%s %s\n  License:   %s\n  Copyright: %s\n  Website:   %s\n\n' \
      "$ga" "$version" "$license" "$copyright" "$url"
  done < "$table"

  while IFS=$'\t' read -r ga version license copyright url files; do
    [[ -z "$ga" || "$ga" == \#* || "$files" == - ]] && continue
    IFS=, read -ra list <<< "$files"
    for f in "${list[@]}"; do
      printf '\n%s\n%s %s: %s\n%s\n\n' \
        "------------------------------------------------------------------------------" \
        "$ga" "$version" "${f##*/}" \
        "------------------------------------------------------------------------------"
      if [[ "$f" == packaging/* ]]; then
        cat "$root/$f"
      else
        jar=$(jar_of "$ga" "$version")
        [ -f "$jar" ] || { echo "missing $jar; build the project first" >&2; exit 1; }
        unzip -p "$jar" "$f" | tr -d '\r'
      fi
    done
  done < "$table"

  printf '\n%s\nApache License, Version 2.0 (applies to every component above marked Apache-2.0)\n%s\n\n' \
    "==============================================================================" \
    "=============================================================================="
  cat "$root/packaging/third-party/Apache-2.0.txt"
} > "$tmp/notices"

if $check; then
  if ! diff -u --label THIRD-PARTY-NOTICES --label generated "$target" "$tmp/notices"; then
    echo "THIRD-PARTY-NOTICES is stale: run packaging/third-party-notices.sh" >&2
    exit 1
  fi
  echo "THIRD-PARTY-NOTICES is up to date" >&2
else
  cp "$tmp/notices" "$target"
  echo "wrote $target" >&2
fi
