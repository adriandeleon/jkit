#!/usr/bin/env bash
# Builds THIRD-PARTY-NOTICES, the notices for the libraries compiled into the jkit binary.
#
#   packaging/third-party-notices.sh          rewrite THIRD-PARTY-NOTICES
#   packaging/third-party-notices.sh --check  fail if it is stale (CI runs this)
#
# The component list is packaging/third-party/components.tsv. Both modes first ask Maven for the
# runtime dependencies of jkit-cli and fail if they differ from that list, so a dependency change
# can't ship without its notices. NOTICE and license texts are copied verbatim out of the jars in
# the local Maven repository (MAVEN_REPO, default ~/.m2/repository), so run a build first.
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
table="$root/packaging/third-party/components.tsv"
target="$root/THIRD-PARTY-NOTICES"
repo=${MAVEN_REPO:-$HOME/.m2/repository}
check=false
case "${1:-}" in
  --check) check=true ;;
  "") ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# 1. The dependency set Maven resolves must match the table.
# compile in the same run, so jkit's own modules resolve from the reactor rather than a repository
# (they are never installed in CI, and a set version like 0.0.0-dev.12 exists nowhere)
(cd "$root" && ./mvnw -B -C -q -pl jkit-cli -am compile dependency:list -DincludeScope=runtime \
  -DexcludeGroupIds=dev.jkit -DoutputFile="$tmp/deps.txt" -DappendOutput=true) >&2
awk -F: '/^ +[^ ]+:[^ ]+:/ { sub(/^ +/, ""); print $1 ":" $2 ":" $4 }' "$tmp/deps.txt" \
  | sort -u > "$tmp/resolved"
awk -F'\t' '!/^#/ && NF { print $1 ":" $2 }' "$table" | sort -u > "$tmp/listed"
if ! diff -u --label components.tsv --label maven "$tmp/listed" "$tmp/resolved" >&2; then
  echo "the runtime dependencies changed: update $table (license, copyright, notice files)" >&2
  echo "and run packaging/third-party-notices.sh" >&2
  exit 1
fi

# 1b. The Debian copyright file names every component too (group/artifact), so it can't fall behind.
deb_copyright="$root/jkit-cli/src/deb/doc/copyright"
missing=0
while IFS=: read -r g a _; do
  if ! grep -qF "$g/$a" "$deb_copyright"; then
    echo "$deb_copyright doesn't mention $g/$a" >&2
    missing=1
  fi
done < "$tmp/listed"
if [ "$missing" = 1 ]; then
  echo "add a Files: stanza for each to $deb_copyright" >&2
  exit 1
fi
# ...and nothing else: each path it names is a listed component, or code embedded in one
# (group/artifact/name), or the Java runtime
extra=0
while IFS= read -r path; do
  case "$path" in '*'|openjdk/java-runtime) continue ;; esac
  ga=$(printf '%s\n' "$path" | cut -d/ -f1,2)
  if ! grep -qxF "${ga%%/*}:${ga#*/}" <(cut -d: -f1,2 "$tmp/listed"); then
    echo "$deb_copyright names $path, which isn't in the binary" >&2
    extra=1
  fi
done < <(awk '/^Files:/{f=1; sub(/^Files: */,""); print; next} f && /^ [^ .]/ && !/:/{sub(/^ +/,""); print; next} {f=0}' "$deb_copyright")
if [ "$extra" = 1 ]; then
  echo "remove those stanzas from $deb_copyright (or list the component in components.tsv)" >&2
  exit 1
fi

# 1c. Code embedded in a component (ANTLR in tomlj, ...) is listed by version in sbom-runtime.py:
# a bump of the component must update that list too.
python3 -I "$root/packaging/sbom-runtime.py" --check-embedded "$table"

# 2. Render the notices.
jar_of() { # group:artifact version
  local g=${1%%:*} a=${1#*:}
  echo "$repo/${g//.//}/$a/$2/$a-$2.jar"
}

{
  cat <<'EOF'
jkit third-party notices
========================

The jkit binary is compiled ahead of time with GraalVM Native Image. Besides jkit's own code
(MIT License, see LICENSE), it contains the libraries listed below under their own licenses, and
parts of the Java runtime: the OpenJDK class library and GraalVM's Substrate VM, licensed under
the GNU General Public License version 2 with the Classpath Exception (full text near the end),
with the third-party code they carry (XML parser, Unicode data, zlib and others; see "Java
runtime").

The binaries are built with GraalVM Community Edition 25.0.5
(https://github.com/graalvm/graalvm-ce-builds), except the macOS x64 binary, which is built with
BellSoft Liberica Native Image Kit 25.0.5 (https://github.com/bell-sw/LibericaNIK), a build of
the same GraalVM Community code.

This file is generated by packaging/third-party-notices.sh; do not edit it by hand.

Components
----------

EOF
  while IFS=$'\t' read -r ga version license copyright url files; do
    [[ -z "$ga" || "$ga" == \#* ]] && continue
    printf '%s %s\n  License:   %s\n  Copyright: %s\n  Website:   %s\n\n' \
      "$ga" "$version" "$license" "$copyright" "$url"
  done < "$table"

  while IFS=$'\t' read -r ga version license copyright url files; do
    [[ -z "$ga" || "$ga" == \#* || "$files" == - ]] && continue
    IFS=, read -ra list <<< "$files"
    for f in "${list[@]}"; do
      printf '\n%s\n%s %s: %s\n%s\n\n' \
        "------------------------------------------------------------------------------" \
        "$ga" "$version" "${f##*/}" \
        "------------------------------------------------------------------------------"
      if [[ "$f" == packaging/* ]]; then
        cat "$root/$f"
      else
        jar=$(jar_of "$ga" "$version")
        [ -f "$jar" ] || { echo "missing $jar; build the project first" >&2; exit 1; }
        unzip -p "$jar" "$f" | tr -d '\r'
      fi
    done
  done < "$table"

  # the Java runtime parts compiled into the binary: copies of the OpenJDK 25 legal files
  # (legal/java.base, legal/java.xml), kept in packaging/third-party/jdk
  printf '\n%s\nJava runtime\n%s\n\n' \
    "==============================================================================" \
    "=============================================================================="
  cat <<'EOF'
Source code: the source of the OpenJDK and GraalVM code in this binary is published at
https://github.com/openjdk/jdk25u and https://github.com/oracle/graal (the tags matching the
versions above). For three years after a jkit release, the maintainer will also send you that
source on request: open an issue at https://github.com/adriandeleon/jkit/issues.

The OpenJDK class library includes third-party code under the notices that follow.
EOF
  for f in ADDITIONAL_LICENSE_INFO ASSEMBLY_EXCEPTION icu.md cldr.md unicode.md zlib.md aes.md \
           siphash.md public_suffix.md xerces.md xalan.md jcup.md dom.md wepoll.md; do
    printf '\n%s\nOpenJDK: %s\n%s\n\n' \
      "------------------------------------------------------------------------------" "$f" \
      "------------------------------------------------------------------------------"
    tr -d '\r' < "$root/packaging/third-party/jdk/$f"
  done

  printf '\n%s\nGNU General Public License, version 2, with the Classpath Exception (OpenJDK, GraalVM)\n%s\n\n' \
    "==============================================================================" \
    "=============================================================================="
  tr -d '\r' < "$root/packaging/third-party/jdk/LICENSE-GPLv2-CE.txt"

  printf '\n%s\nApache License, Version 2.0 (applies to every component above marked Apache-2.0)\n%s\n\n' \
    "==============================================================================" \
    "=============================================================================="
  cat "$root/packaging/third-party/Apache-2.0.txt"
} > "$tmp/notices"

if $check; then
  if ! diff -u --label THIRD-PARTY-NOTICES --label generated "$target" "$tmp/notices"; then
    echo "THIRD-PARTY-NOTICES is stale: run packaging/third-party-notices.sh" >&2
    exit 1
  fi
  echo "THIRD-PARTY-NOTICES is up to date" >&2
else
  cp "$tmp/notices" "$target"
  echo "wrote $target" >&2
fi
